export const COMPACT_SUMMARY_PROMPT = `你的任务是把到目前为止的对话总结成一份详细摘要，用于在新的上下文中准确延续会话。

先在 <analysis> 标签内按时间顺序梳理对话：用户的每个显式请求与意图、你的处理方式、关键技术决策、涉及的文件与代码（含关键片段）、遇到的错误与修复方式（特别注意用户纠正过你的地方）。检查完整性后，在 <summary> 标签内按以下九节输出：

1. 任务与意图：用户所有显式请求和目标，逐条列出
2. 关键技术概念：涉及的技术、框架、约定
3. 文件与代码：查看/修改/创建过的具体文件，重要处附代码片段并说明其作用
4. 错误与修复：遇到的所有错误、修复方式；用户明确要求改做法的反馈要单独标注
5. 问题解决：已解决的问题与仍在排查的事项
6. 全部用户消息：列出所有非工具结果的用户消息原文（理解用户意图变化的关键）
7. 待办任务：用户明确交代但尚未完成的事项
8. 当前工作：摘要前一刻正在做什么，精确到文件与代码
9. 下一步（可选）：与最近工作直接相关的下一步；必须逐字引用最近对话中的任务描述，确保方向不漂移

若遇到 <whycode-turn-aborted>：标记之前尚未完成的用户请求已经停止，只能作为历史背景。第 6 节可保留并注明“已中断”，但第 7~9 节不得把它列为待办、当前工作或下一步；只有标记之后的用户消息明确恢复时才重新列入。

若输入开头包含 <whycode-project-instructions>，它是应用从当前文件系统精确读取的控制上下文，不属于待总结对话。必须遵守它，但不要在摘要中复述、改写或归纳其中内容；应用会在压缩完成后重新读取并原样注入最新版本。

要求：只输出文本，不要调用任何工具；摘要供你自己续用，务求具体、可执行。`

