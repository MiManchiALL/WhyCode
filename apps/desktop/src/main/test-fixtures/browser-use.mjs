import assert from 'node:assert/strict'
import { createServer } from 'node:http'
import path from 'node:path'
import { mkdir, writeFile } from 'node:fs/promises'
import { pathToFileURL } from 'node:url'
import { app, BrowserWindow, nativeImage, protocol } from 'electron'
import { BrowserGuests } from '../browser-guests.ts'
import { BrowserAgent } from '../browser-agent.ts'

const directory = process.env.WHYCODE_BROWSER_TEST_DIR
app.setPath('userData', path.join(directory, 'profile'))
protocol.registerSchemesAsPrivileged([{ scheme: 'whycode-browser-file', privileges: { standard: true, secure: true, supportFetchAPI: true } }])
const timeout = setTimeout(() => app.exit(1), 80_000)
const server = createServer((_request, response) => response.end(`<!doctype html><html><head><meta charset="utf-8"><title>Browser fixture</title></head><body style="background:#bada55">
  <label>Username <input aria-label="Username" value=""></label>
  <button onclick="document.querySelector('output').textContent=++window.count;document.body.style.background='rgb(100,150,200)'">Increment</button><output>0</output>
  <span onclick="document.body.dataset.palette='chosen'">🎨</span>
  <script>window.count=0;</script></body></html>`))
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
const url = `http://127.0.0.1:${server.address().port}/`
const delay = () => new Promise(resolve => setTimeout(resolve, 30))
async function until(predicate, label) {
  for (let count = 0; count < 300; count++) { if (await predicate()) return; await delay() }
  throw new Error(`等待失败: ${label}`)
}
app.whenReady().then(async () => {
  const guests = new BrowserGuests()
  const agent = new BrowserAgent(guests)
  guests.register(async () => undefined)
  agent.pages.register()
  const win = new BrowserWindow({ show: false, width: 1000, height: 800,
    webPreferences: { preload: path.join(directory, 'preload.cjs'), webviewTag: true, sandbox: true, contextIsolation: true } })
  guests.bind(win)
  const execute = code => win.webContents.executeJavaScript(code)
  const run = (turnId, code, signal = new AbortController().signal, onProgress) => agent.forRuntime('alpha').execute(code, { turnId, toolCallId: turnId, abortSignal: signal, onProgress })
  const finish = turnId => agent.forRuntime('alpha').finishTurn(turnId)
  await win.loadFile(path.join(directory, 'index.html'))
  await until(() => execute('!!window.fixture'), 'fixture')
  win.setOpacity(0)
  win.setSkipTaskbar(true)
  win.showInactive()
  const coldFile = path.join(directory, 'cold.html')
  await writeFile(coldFile, '<!doctype html><title>Cold file</title><body style="background:#bada55"><button>Ready</button>')
  const cold = await run('cold', `await browser.open({url:${JSON.stringify(pathToFileURL(coldFile).href)}}); text(await browser.snapshot()); image(await browser.screenshot());`)
  assert.equal(cold.isError, false, cold.text)
  assert.equal(win.isVisible(), true)
  assert.equal(win.isFocused(), false, '截图不激活宿主窗口')
  await finish('cold')
  assert.equal(win.webContents.getBackgroundThrottling(), true, '隐藏 Agent 页结束后恢复宿主节流')
  win.hide()
  win.setOpacity(1)
  await execute('fixture.session("alpha")')
  await until(() => execute('fixture.state().tabs.length===0'), 'clear cold descriptor')
  await execute(`fixture.open(${JSON.stringify(url)})`)
  await until(() => agent.pages.list('alpha').some(page => guests.get(page.id)?.getURL() === url), 'user page')
  const original = agent.pages.list('alpha')[0]
  const originalGuest = guests.get(original.id)
  originalGuest.setZoomFactor(1.5)
  await originalGuest.executeJavaScript('document.querySelector("input").value="user-draft"')
  const first = await run('one', `await browser.open({url:${JSON.stringify(url)}}); text(await browser.evaluate({expression:'document.querySelector("input").value'}));`)
  assert.equal(first.isError, false, first.text)
  assert.match(first.text, /user-draft/)
  assert.equal(agent.pages.current('one').surfaceId, original.id, '优先接管已有用户 DOM')
  assert.deepEqual(await originalGuest.executeJavaScript('[innerWidth,innerHeight]'), [1280, 800], 'fixed viewport')
  const changed = await run('one', `const s=await browser.snapshot(); await browser.fill({ref:s.nodes.find(n=>n.role==='textbox').ref,value:'agent-draft'}); await browser.click({ref:s.nodes.find(n=>n.role==='button').ref}); image(await browser.screenshot());`)
  assert.equal(changed.isError, false, changed.text)
  assert.equal(changed.images.length, 1)
  assert.deepEqual(nativeImage.createFromBuffer(changed.images[0].bytes).getSize(), { width: 1280, height: 800 })
  const changedBitmap = nativeImage.createFromBuffer(changed.images[0].bytes).toBitmap()
  assert.deepEqual([...changedBitmap.subarray(-4, -1)], [200, 150, 100], '截图包含本次点击后的画面')
  assert.equal(await originalGuest.executeJavaScript('document.querySelector("input").value'), 'agent-draft')
  assert.equal(await originalGuest.executeJavaScript('document.querySelector("output").textContent'), '1')
  const keyboard = await run('one', 'const s=await browser.snapshot(); await browser.click({ref:s.nodes.find(n=>n.role==="textbox").ref}); await browser.press({key:"Control+A"}); await browser.type({text:"typed"});')
  assert.equal(keyboard.isError, false, keyboard.text)
  assert.equal(await originalGuest.executeJavaScript('document.querySelector("input").value'), 'typed')
  const textClick = await run('one', 'const s=await browser.snapshot(); text(s.nodes.filter(n=>n.role==="generic"&&!n.name)); await browser.click({ref:s.nodes.find(n=>n.role==="StaticText"&&n.name==="🎨").ref});')
  assert.equal(textClick.isError, false, textClick.text)
  assert.ok(textClick.text.startsWith('[]'), '快照省略无名称的布局容器')
  assert.equal(await originalGuest.executeJavaScript('document.body.dataset.palette'), 'chosen', '文字引用点击其所属真实元素')
  const invalidWait = await run('one', 'await browser.wait({timeoutMs:5});')
  assert.match(invalidWait.text, /ref 或 text/)
  const invalidExpression = await run('one', 'await browser.evaluate(() => document.title);')
  assert.match(invalidExpression.text, /不能传入函数/)
  assert.equal(win.isVisible(), false, '浏览器操作不显示宿主窗口')
  if (process.env.WHYCODE_BROWSER_REVIEW_DIR) {
    await mkdir(process.env.WHYCODE_BROWSER_REVIEW_DIR, { recursive: true })
    await writeFile(path.join(process.env.WHYCODE_BROWSER_REVIEW_DIR, 'agent.png'), changed.images[0].bytes)
    await execute('fixture.narrow()')
    await until(() => execute('document.querySelector("[aria-label=\'Agent 浏览器\']").getBoundingClientRect().width===300'), 'narrow viewport')
    await writeFile(path.join(process.env.WHYCODE_BROWSER_REVIEW_DIR, 'narrow.png'), (await win.webContents.capturePage()).toPNG())
  }
  await execute(`document.querySelector('[aria-label="切换到我的网页"]').click()`)
  await until(() => agent.pages.list('alpha').length === 2, 'personal copy')
  const personal = agent.pages.list('alpha').find(page => !page.agent)
  await until(() => guests.get(personal.id)?.getURL() === url, 'personal copy load')
  assert.equal(await guests.get(personal.id).executeJavaScript('document.querySelector("input").value'), '')
  await execute(`fixture.open(${JSON.stringify(url + 'second')})`)
  assert.equal(await execute('fixture.state().tabs.length'), 1, '新建浏览器复用 Agent 外层入口')
  await until(() => guests.get(personal.id)?.getURL() === url + 'second', 'user navigation')
  assert.equal(originalGuest.getURL(), url)
  await execute('fixture.file()')
  await execute(`fixture.reference(${JSON.stringify(url)})`)
  await until(() => execute('!!document.querySelector(\'[aria-label="退出引用"]\')'), 'file reference enters personal page')
  assert.equal(await execute('fixture.state().tabs.length'), 2, '保留文件标签，浏览器入口仍然只有一个')
  assert.ok(!originalGuest.isDestroyed())
  await execute('fixture.close()')
  await until(() => !guests.get(personal.id), 'close personal view')
  assert.equal(agent.pages.current('one').abort.signal.aborted, false, '关闭用户界面不停止 Agent')
  await execute('fixture.session("beta")')
  await until(() => !guests.get(personal.id), 'ordinary page released on switch')
  assert.ok(!originalGuest.isDestroyed())
  const background = await run('one', 'const s=await browser.snapshot(); await browser.click({ref:s.nodes.find(n=>n.role===\'button\').ref}); image(await browser.screenshot());')
  assert.equal(background.isError, false, background.text)
  assert.equal(await originalGuest.executeJavaScript('document.querySelector("output").textContent'), '2')
  assert.ok(background.images[0].bytes.length > 1000)
  const other = await agent.forRuntime('beta').execute(`await browser.open({url:${JSON.stringify(url)}})`, {
    turnId: 'other', toolCallId: 'other', abortSignal: new AbortController().signal,
  })
  assert.equal(other.isError, false, other.text)
  await finish('one')
  assert.equal(originalGuest.isDestroyed(), true, '隐藏 Agent 页面 Turn 结束销毁')
  assert.equal(win.webContents.getBackgroundThrottling(), false, '另一个会话仍在使用浏览器时不提前恢复节流')
  await agent.forRuntime('beta').finishTurn('other')
  assert.equal(win.webContents.getBackgroundThrottling(), true)

  await execute('fixture.session("alpha")')
  await execute(`fixture.open(${JSON.stringify(url)})`)
  await until(() => agent.pages.list('alpha').some(page => guests.get(page.id)?.getURL() === url), 'handoff user')
  const handoff = agent.pages.list('alpha')[0]
  const handoffGuest = guests.get(handoff.id)
  handoffGuest.setZoomFactor(1.5)
  assert.equal((await run('two', 'await browser.open(); await browser.evaluate({expression:\'document.querySelector("input").value="preserved"\'});')).isError, false)
  await until(() => execute('!!document.querySelector(\'[aria-label="切换到我的网页"]\')'), 'agent switch')
  await finish('two')
  assert.equal(win.webContents.getBackgroundThrottling(), true, '网页交还用户后恢复宿主节流')
  assert.equal(handoffGuest.isDestroyed(), false, '用户观看中的网页原样交还')
  assert.equal(await handoffGuest.executeJavaScript('document.querySelector("input").value'), 'preserved')
  assert.ok(Math.abs(handoffGuest.getZoomFactor() - 1.5) < 0.001, '交还时恢复用户缩放')
  await until(() => execute('!document.querySelector(\'[aria-label="切换到我的网页"]\')'), 'switch removed')
  assert.equal((await run('three', 'await browser.open(); text(await browser.evaluate({expression:\'document.querySelector("input").value\'}));')).text.includes('preserved'), true)
  let waiting
  const waitStarted = new Promise(resolve => { waiting = resolve })
  const pending = run('three', 'text(await browser.snapshot()); await browser.wait({text:"never appears",timeoutMs:10000}); await browser.click({ref:"unreachable"});',
    undefined, message => { if (message === '浏览器：wait') waiting() })
  await waitStarted
  await execute('fixture.close()')
  await until(() => execute('!!document.querySelector(\'[role="alertdialog"]\')'), 'close confirmation')
  await execute(`Array.from(document.querySelectorAll('[role="alertdialog"] button')).find(b=>b.textContent==='停止并继续').click()`)
  const stopped = await pending
  assert.equal(stopped.isError, true, stopped.text)
  assert.match(stopped.text, /user_closed/)
  assert.match(stopped.text, /completed/)
  assert.match(stopped.text, /uncertain/)
  assert.equal(win.webContents.getBackgroundThrottling(), true, '用户关闭时立即释放绘制活动')
  assert.doesNotMatch(stopped.text, /"operation":"click"/)
  assert.equal((await run('three', `await browser.open({url:${JSON.stringify(url)}})`)).isError, true, '用户关闭后同 Turn 不自动重建')
  await finish('three')
  await until(() => agent.pages.list('alpha').length === 0, 'all pages closed')
  await execute('fixture.visible(false)')
  const hidden = await run('four', `await browser.open({url:${JSON.stringify(url)}}); image(await browser.screenshot());`)
  assert.equal(hidden.isError, false, hidden.text)
  assert.equal(await execute('fixture.state().open'), false, '后台打开不展开侧栏')
  assert.ok(hidden.images[0].bytes.length > 1000)
  const bitmap = nativeImage.createFromBuffer(hidden.images[0].bytes).toBitmap()
  const corner = (799 * 1280 + 1279) * 4
  assert.deepEqual([...bitmap.subarray(corner, corner + 3)], [85, 218, 186], '新后台页面截图包含真实内容')
  const file = path.join(directory, 'local.html')
  await writeFile(file, '<!doctype html><title>Local page</title><h1>Local content</h1>')
  const navigation = await run('four', `const s=await browser.snapshot(); await browser.navigate({url:${JSON.stringify(pathToFileURL(file).href)}}); text(await browser.evaluate({expression:'document.querySelector("h1").textContent'})); await browser.click({ref:s.nodes.find(n=>n.role==='button').ref});`)
  assert.equal(navigation.isError, true)
  assert.match(navigation.text, /Local content/)
  assert.match(navigation.text, /元素引用已失效/)
  assert.equal(agent.pages.surface(agent.pages.current('four')).page.workspaceFile, true)
  await until(() => execute(`fixture.state().tabs.some(tab=>tab.page.url===${JSON.stringify(pathToFileURL(file).href)} && tab.page.workspaceFile)`), 'hidden navigation updates descriptor')
  await finish('four')
  assert.equal(agent.pages.list('alpha').length, 0)
  assert.equal((await run('five', `await browser.open({url:${JSON.stringify(url)}})`)).isError, false)
  await execute('window.whycode.clearBrowserData("all")')
  assert.equal(win.webContents.getBackgroundThrottling(), true, '全部清理释放绘制活动')
  assert.equal(agent.pages.list('alpha').length, 0, '全部清理释放 Agent 网页')
  assert.equal((await run('five', `await browser.open({url:${JSON.stringify(url)}})`)).isError, true, '清理后旧 Turn 不能恢复写入')
  await finish('five')
  win.destroy()
  clearTimeout(timeout)
  server.close()
  process.stdout.write('browser use passed\n')
  app.exit(0)
}).catch(error => { process.stderr.write(`${error.stack}\n`); server.close(); app.exit(1) })
