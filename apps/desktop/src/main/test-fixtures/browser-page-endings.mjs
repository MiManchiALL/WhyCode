import assert from 'node:assert/strict'

export async function checkBrowserPageEndings({ run, finish, execute, until, agent, guests, url }) {
  await execute('fixture.visible(false)')
  assert.equal((await run('collapsed', `await browser.open({url:${JSON.stringify(url)}});`)).isError, false)
  await until(() => execute('fixture.state().tabs.length===1'), 'unviewed page registered')
  const collapsed = guests.get(agent.pages.current('collapsed').surfaceId)
  await collapsed.executeJavaScript('document.querySelector("input").value="agent-result"')
  await finish('collapsed')
  assert.equal(collapsed.isDestroyed(), false, '从未查看过的标签也保留操作结果')
  assert.equal(await execute('fixture.state().open'), false, '后台登记不打开侧栏')
  await execute('fixture.visible(true)')
  await until(() => agent.pages.list('alpha').some(page => page.active), 'handed-back page visible')
  assert.equal(await collapsed.executeJavaScript('document.querySelector("input").value'), 'agent-result')

  assert.equal((await run('personal', 'await browser.open();')).isError, false)
  await execute(`fixture.open(${JSON.stringify(url)})`)
  await until(() => agent.pages.list('alpha').some(page => !page.agent && guests.get(page.id)?.getURL() === url), 'independent personal page')
  const personal = guests.get(agent.pages.list('alpha').find(page => !page.agent).id)
  await personal.executeJavaScript('document.querySelector("input").value="my-draft"')
  await finish('personal')
  assert.equal(collapsed.isDestroyed(), false)
  assert.equal(personal.isDestroyed(), false)
  assert.equal(await personal.executeJavaScript('document.querySelector("input").value'), 'my-draft', '交还 Agent 页不覆盖独立用户页')
  assert.equal(await collapsed.executeJavaScript('document.querySelector("input").value'), 'agent-result')

  assert.equal((await run('away', 'await browser.open();')).isError, false)
  await execute('fixture.session("beta")')
  await until(() => !agent.pages.list('alpha').some(page => page.active), 'session switched away')
  await until(() => collapsed.isDestroyed(), 'ordinary page released on session switch')
  assert.equal(personal.isDestroyed(), false, '仍在运行的 Agent 不因切换会话停止')
  const background = await run('away', `await browser.open({url:${JSON.stringify(url + 'background')}});`)
  assert.equal(background.isError, false, background.text)
  await until(() => execute('fixture.saved("alpha").tabs.length===3'), 'page opened while another session is visible is stored in its own session')
  assert.equal(await execute('fixture.state().tabs.length'), 0, '不写入正在查看的其它会话')
  await finish('away')
  assert.equal(personal.isDestroyed(), true, '非当前会话结束时释放 DOM')
  assert.equal(await execute('fixture.saved("alpha").tabs.length'), 3, '保留全部标签地址')
  await execute('fixture.resume("alpha")')
  await until(() => agent.pages.list('alpha').some(page => guests.get(page.id)?.getURL() === url + 'background'), 'restored session reloads selected tab')
  assert.equal(await execute('fixture.state().tabs.length'), 3)
  const reloaded = guests.get(agent.pages.list('alpha')[0].id)
  assert.equal(await reloaded.executeJavaScript('document.querySelector("input").value'), '', '会话切换允许按 URL 重新加载')
  await execute('fixture.session("alpha")')

  assert.equal((await run('crashed', `await browser.open({url:${JSON.stringify(url)}});`)).isError, false)
  const crashed = guests.get(agent.pages.current('crashed').surfaceId)
  let waiting
  const started = new Promise(resolve => { waiting = resolve })
  const pending = run('crashed', 'await browser.wait({text:"never appears",timeoutMs:10000});', undefined,
    message => { if (message === '浏览器：wait') waiting() })
  await started
  crashed.forcefullyCrashRenderer()
  const result = await pending
  assert.equal(result.isError, true)
  assert.match(result.text, /page_crashed/)
  assert.doesNotMatch(result.text, /user_closed/)
  await until(() => crashed.isDestroyed(), 'crashed guest released')
  await finish('crashed')

  await execute('fixture.session("alpha")')
  const capacity = await run('capacity', `for(let i=0;i<12;i++) await browser.open({url:${JSON.stringify(url)}+i}); await browser.open({url:${JSON.stringify(url + 'overflow')}});`)
  assert.equal(capacity.isError, true)
  assert.match(capacity.text, /标签页已满/)
  assert.equal(agent.pages.list('alpha').length, 12, '达到标签上限后不创建无入口的物理页')
  await until(() => execute('fixture.state().tabs.length===12'), 'all controlled pages have tabs')
  await finish('capacity')
  assert.equal(agent.pages.list('alpha').every(page => !page.agent), true)
  await execute('fixture.session("alpha")')
}
